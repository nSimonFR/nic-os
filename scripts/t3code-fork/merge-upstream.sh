#!/usr/bin/env bash
# Merge an upstream t3code nightly into the Issues fork, in a checkout of
# nSimonFR-ai/t3code with remotes `origin` (the fork) and `up` (pingdotgg).
#
#   merge-upstream.sh <version>     e.g. 0.1.8-nightly.20261107.4301
#
# Leaves the fork branch at one merge commit, not pushed. Exit 10 when the merge
# conflicts beyond pnpm-lock.yaml: that one needs a person (or an agent) and the
# fork's spec.md.
set -euo pipefail

version=${1:?version}
tag=v$version
here=$(cd "$(dirname "$0")" && pwd)
branch=nicos/issues-nightly-${version%%-*}

git fetch -q --force up "refs/tags/$tag:refs/tags/$tag"
git fetch -q origin '+refs/heads/*:refs/remotes/origin/*'

if git rev-parse -q --verify "origin/$branch" >/dev/null; then
  git checkout -q -B "$branch" "origin/$branch"
else
  base=$(git for-each-ref --format='%(refname:strip=3)' 'refs/remotes/origin/nicos/issues-nightly-*' |
    grep -E '^nicos/issues-nightly-[0-9]+\.[0-9]+\.[0-9]+$' | sort -V | tail -1)
  echo "new branch $branch from $base"
  git checkout -q -B "$branch" "origin/$base"
fi

if git merge-base --is-ancestor "$tag" HEAD; then
  echo "$tag is already merged into $branch"
  exit 0
fi

orig=$(git rev-parse HEAD)
git checkout -q -B tmp-merge "$orig"
node "$here/migrations.mjs" detach
git -c user.name=nSimonFR-ai -c user.email=265587706+nSimonFR-ai@users.noreply.github.com \
  commit -q --no-verify -am "tmp: detach issue migrations"

if ! git merge --no-ff --no-commit "$tag" >/dev/null; then
  # The lockfile is regenerated by the install that follows; take upstream's.
  git checkout --theirs pnpm-lock.yaml 2>/dev/null && git add pnpm-lock.yaml || true
  conflicts=$(git diff --name-only --diff-filter=U)
  if [ -n "$conflicts" ]; then
    echo "::error::merge of $tag conflicts in:"
    echo "$conflicts"
    git merge --abort || true
    git checkout -q -B "$branch" "$orig"
    exit 10
  fi
fi

# The fork keeps its own .github/workflows: its token cannot push upstream's.
git rm -rq --ignore-unmatch .github/workflows
git checkout "origin/main" -- .github/workflows
node "$here/migrations.mjs" attach

# Upstream's nightly this branch is based on.
sed -i -E "0,/^Current base: \`v[^\`]+\`/s//Current base: \`$tag\`/" spec.md
sed -i -E "0,/\(pingdotgg\/t3code \`main\` at \`[0-9a-f]+\`\)/s//(pingdotgg\/t3code \`main\` at \`$(git rev-parse --short=10 "$tag^{commit}")\`)/" spec.md

git add -A
tree=$(git write-tree)
commit=$(git -c user.name=nSimonFR-ai -c user.email=265587706+nSimonFR-ai@users.noreply.github.com \
  commit-tree "$tree" -p "$orig" -p "$tag^{commit}" \
  -m "merge: pingdotgg/t3code $tag into the nic-os Issues fork")
git checkout -q -B "$branch" "$commit"
git branch -q -D tmp-merge
git log --oneline -1
